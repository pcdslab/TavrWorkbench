"""Everything read from / written to the output folder (no Slicer imports).

<output>/
    review_status.json            segmentation progress  {cid: {overall, time, mask_edited, mask_saved_at}}
    correction_status.json        measurement progress   {cid: {status, time, planes_edited, heights_edited}}
    annotations.csv               one row per case: every Approve/Flag rating + comment
    corrected_measurements.csv    one row per case+plane: contour metrics
    corrected_heights.csv         one row per case+height: heights above the (corrected) annulus plane
    tavr_workbench.log
    <case_id>/
        review.json               full review of the case (both modes)
        segmentation.seg.nrrd     edited mask (only after "Save mask")
        <plane>_contour.mrk.json  corrected contour (+ _max_d / _min_d diameter lines)
        height_<key>.mrk.json     corrected height (stj / lch / rch; extra markups of the same file: _1, _2 ...)
        annular_plane/            hinge points + annulus contour/diameters + heights regenerated by the
                                  Annular Plane tab; they replace the data-map files for this case
        archive/v1, v2 ...        what was in effect before each Annular Plane "Apply" (+ manifest.json)
    annular_plane_fixes.csv       one row per Apply: hinge points, new annulus metrics and heights
"""
import csv
import glob
import json
import os
import shutil
from datetime import datetime

from .constants import (ANNOTATION_COLUMNS, ANNOTATIONS_CSV, ARCHIVE_DIR, PLANE_DIR, PLANE_FILES,
                        PLANE_FIX_COLUMNS, PLANE_FIXES_CSV, CASE_MASK_FILE, CASE_REVIEW_FILE,
                        CONTOUR_FILE_SUFFIX, HEIGHT_COLUMNS, HEIGHT_FILE_PREFIX, HEIGHTS_CSV,
                        MEAS_STATUS_FILE, MEASUREMENT_COLUMNS, MEASUREMENTS_CSV,
                        MEASUREMENT_KEY_TO_LABEL, RATING_NONE, RATING_TO_STR, SEG_STATUS_FILE,
                        SEGMENTATION_LABELS, normalize_rating, normalize_review)


def now_iso():
    return datetime.now().isoformat(timespec="seconds")


def safe_name(name):
    safe = "".join(c for c in str(name) if c.isalnum() or c in ("_", "-", ".")).strip()
    return safe or "unknown_case"


def _write_json(path, data):
    tmp = path + ".tmp"
    with open(tmp, "w") as f:
        json.dump(data, f, indent=2)
    os.replace(tmp, path)


def _read_csv(path, key_fn):
    rows = {}
    if os.path.exists(path):
        try:
            with open(path, newline="") as f:
                for r in csv.DictReader(f):
                    rows[key_fn(r)] = r
        except Exception as e:
            print(f"[TavrWorkbench] WARNING: could not read {path}: {e}")
    return rows


def _write_csv(path, cols, rows):
    tmp = path + ".tmp"
    with open(tmp, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=cols, extrasaction="ignore")
        w.writeheader()
        w.writerows(rows)
    os.replace(tmp, path)


class OutputStore:
    def __init__(self):
        self.root = ""
        self.seg_status = {}
        self.meas_status = {}

    # ---------------------------------------------------------------- paths
    def set_root(self, root):
        self.root = str(root or "")
        self.reload()

    def path(self, *parts):
        return os.path.join(self.root, *parts) if self.root else ""

    def case_dir(self, cid):
        return self.path(safe_name(cid))

    def ensure_case_dir(self, cid):
        d = self.case_dir(cid)
        os.makedirs(d, exist_ok=True)
        return d

    def case_path(self, cid, filename):
        return os.path.join(self.case_dir(cid), filename) if self.root else ""

    def contour_path(self, cid, plane, key):
        return self.case_path(cid, f"{plane}_{CONTOUR_FILE_SUFFIX[key]}.mrk.json")

    def find_saved_contour(self, cid, plane):
        """Corrected contour from an earlier session (also finds folders written by the old
        correct_measurements module, which used the raw case id as folder name)."""
        if not self.root:
            return None
        name = f"{plane}_{CONTOUR_FILE_SUFFIX['curve']}.mrk.json"
        for d in (self.case_dir(cid), self.path(str(cid))):
            p = os.path.join(d, name)
            if os.path.isfile(p):
                return p
        return None

    def height_path(self, cid, key, part=0):
        """Corrected height file. `part` > 0 is for extra markups that were stored in the same source file."""
        suffix = f"_{part}" if part else ""
        return self.case_path(cid, f"{HEIGHT_FILE_PREFIX}_{key}{suffix}.mrk.json")

    def find_saved_height(self, cid, key, part=0):
        """Corrected height from an earlier session, or None."""
        path = self.height_path(cid, key, part) if self.root else ""
        return path if path and os.path.isfile(path) else None

    # ------------------------------------------------------- annular plane
    def plane_dir(self, cid):
        return os.path.join(self.case_dir(cid), PLANE_DIR) if self.root else ""

    def plane_file(self, cid, sample_key):
        """Regenerated file for ('contours', 'annulus') etc. inside annular_plane/ (may not exist yet)."""
        return os.path.join(self.plane_dir(cid), PLANE_FILES[sample_key]) if self.root else ""

    def effective_sample(self, sample, cid):
        """`sample` with the data-map paths replaced by this case's regenerated Annular Plane files
        (hinge points, annulus contour + diameters, heights), when it has been fixed."""
        if not self.root or not os.path.isdir(self.plane_dir(cid)):
            return sample
        out = dict(sample)
        for (group, name), _file in PLANE_FILES.items():
            path = self.plane_file(cid, (group, name))
            if os.path.isfile(path):
                out[group] = dict(out.get(group) or {}, **{name: path})
        return out

    def plane_fix_version(self, cid):
        return int(self.meas_status.get(str(cid), {}).get("plane_fix_version", 0) or 0)

    def next_archive_dir(self, cid):
        """archive/v<N+1> (N = highest existing version), not yet created."""
        base = os.path.join(self.case_dir(cid), ARCHIVE_DIR)
        versions = [int(os.path.basename(p)[1:]) for p in glob.glob(os.path.join(base, "v*"))
                    if os.path.basename(p)[1:].isdigit()]
        version = max(versions + [0]) + 1
        return version, os.path.join(base, f"v{version}")

    def saved_corrections_superseded_by_plane_fix(self, cid):
        """Saved Measurements corrections made for the OLD plane: annulus contour/diameters + heights."""
        paths = [self.contour_path(cid, "annulus", key) for key in ("curve", "max", "min")]
        paths += glob.glob(os.path.join(self.case_dir(cid), "height_*.mrk.json"))
        return [p for p in paths if p and os.path.isfile(p)]

    def archive_before_plane_fix(self, cid, sample_in_effect):
        """Back up everything the fix replaces into archive/v<N>: the files currently in effect
        ('current/') and the saved corrections for the old plane ('saved_corrections/', moved
        out so they no longer override the regenerated files). Returns (version, archive_dir, manifest)."""
        version, adir = self.next_archive_dir(cid)
        os.makedirs(os.path.join(adir, "current"), exist_ok=True)
        manifest = {"case_id": str(cid), "version": version, "archived_at": now_iso(),
                    "current": {}, "saved_corrections": {}}
        for (group, name), file_name in PLANE_FILES.items():
            src = (sample_in_effect.get(group) or {}).get(name)
            if isinstance(src, str) and os.path.isfile(src):
                shutil.copy2(src, os.path.join(adir, "current", file_name))
                manifest["current"][file_name] = src
        corrections = self.saved_corrections_superseded_by_plane_fix(cid)
        if corrections:
            os.makedirs(os.path.join(adir, "saved_corrections"), exist_ok=True)
            for src in corrections:
                dst = os.path.join(adir, "saved_corrections", os.path.basename(src))
                shutil.move(src, dst)
                manifest["saved_corrections"][os.path.basename(src)] = src
        _write_json(os.path.join(adir, "manifest.json"), manifest)
        return version, adir, manifest

    def record_plane_fix(self, cid, version, archive_dir, manifest, row):
        """After the new files are written: complete the manifest, upsert annular_plane_fixes.csv and
        update correction_status.json (annulus / heights edits now belong to the archived version)."""
        manifest["applied"] = row
        _write_json(os.path.join(archive_dir, "manifest.json"), manifest)
        path = self.path(PLANE_FIXES_CSV)
        rows = _read_csv(path, lambda r: (r.get("case_id", ""), str(r.get("version", ""))))
        rows[(str(cid), str(version))] = dict(row, case_id=str(cid), version=version, archive_dir=archive_dir)
        _write_csv(path, PLANE_FIX_COLUMNS, rows.values())
        entry = self.meas_status.setdefault(str(cid), {})
        entry["plane_fix_version"] = version
        entry["plane_fixed_at"] = row.get("applied_at", now_iso())
        entry["planes_edited"] = [p for p in entry.get("planes_edited", []) if p != "annulus"]
        entry["heights_edited"] = []
        self.dump()

    def edited_mask_path(self, cid):
        p = self.case_path(cid, CASE_MASK_FILE)
        return p if p and os.path.isfile(p) else ""

    # --------------------------------------------------------------- status
    def reload(self):
        self.seg_status = self._read_status(SEG_STATUS_FILE, "overall")
        self.meas_status = self._read_status(MEAS_STATUS_FILE, "status")

    def _read_status(self, filename, rating_key):
        path = self.path(filename)
        if not path or not os.path.exists(path):
            return {}
        try:
            with open(path) as f:
                data = json.load(f)
        except Exception as e:
            print(f"[TavrWorkbench] WARNING: could not read {path}: {e}")
            return {}
        out = {}
        for cid, entry in (data.items() if isinstance(data, dict) else []):
            if isinstance(entry, dict):
                if rating_key in entry:
                    entry[rating_key] = normalize_rating(entry[rating_key])
                out[str(cid)] = entry
        return out

    def dump(self):
        if not self.root:
            return
        os.makedirs(self.root, exist_ok=True)
        _write_json(self.path(SEG_STATUS_FILE), self.seg_status)
        _write_json(self.path(MEAS_STATUS_FILE), self.meas_status)

    def seg_rating(self, cid):
        return self.seg_status.get(str(cid), {}).get("overall", RATING_NONE)

    def meas_rating(self, cid):
        return self.meas_status.get(str(cid), {}).get("status", RATING_NONE)

    def set_seg_decision(self, cid, rating):
        entry = self.seg_status.setdefault(str(cid), {})
        entry["overall"] = rating
        entry["time"] = now_iso()

    def set_meas_decision(self, cid, rating):
        entry = self.meas_status.setdefault(str(cid), {})
        entry["status"] = rating
        entry["time"] = now_iso()

    def mask_edited(self, cid):
        return bool(self.seg_status.get(str(cid), {}).get("mask_edited"))

    def mark_mask_edited(self, cid):
        entry = self.seg_status.setdefault(str(cid), {})
        entry["mask_edited"] = True
        entry["mask_saved_at"] = now_iso()

    # --------------------------------------------------------- review.json
    def read_review(self, cid):
        path = self.case_path(cid, CASE_REVIEW_FILE)
        if not path or not os.path.exists(path):
            return None
        try:
            with open(path) as f:
                return normalize_review(json.load(f).get("review"))
        except Exception as e:
            print(f"[TavrWorkbench] WARNING: could not read saved review {path}: {e}")
            return None

    def write_review(self, cid, review):
        self.ensure_case_dir(cid)
        _write_json(self.case_path(cid, CASE_REVIEW_FILE),
                    {"case_id": str(cid), "saved_at": now_iso(), "review": review})

    # ----------------------------------------------------------------- CSVs
    def upsert_annotation(self, cid, sample, review, mask_status_text):
        path = self.path(ANNOTATIONS_CSV)
        rows = _read_csv(path, lambda r: r.get("case_id", ""))
        mask_path = self.case_path(cid, CASE_MASK_FILE) if self.mask_edited(cid) else (sample.get("label") or "")
        row = {
            "case_id": str(cid),
            "file": sample.get("image", ""),
            "comment": review.get("comment", ""),
            "mask_path": mask_path,
            "mask_status": mask_status_text,
            "overall": RATING_TO_STR.get(review.get("overall", RATING_NONE), ""),
            "measurements_overall": RATING_TO_STR.get(review.get("measurements_overall", RATING_NONE), ""),
            "saved_at": now_iso(),
        }
        seg = review.get("segmentation", {})
        meas = review.get("measurements", {})
        for label in SEGMENTATION_LABELS:
            row[label] = RATING_TO_STR.get(seg.get(label, RATING_NONE), "")
        for label in MEASUREMENT_KEY_TO_LABEL.values():
            row[label] = RATING_TO_STR.get(meas.get(label, RATING_NONE), "")
        rows[str(cid)] = row
        _write_csv(path, ANNOTATION_COLUMNS, rows.values())

    def upsert_measurements(self, cid, metric_rows, dirty_planes):
        """metric_rows: [{plane, area_mm2, ...}] from MeasurementEditor.metrics_rows()."""
        cid = str(cid)
        entry = self.meas_status.setdefault(cid, {})
        edited = list(entry.get("planes_edited", []))
        for p in dirty_planes:
            if p not in edited:
                edited.append(p)
        entry["planes_edited"] = edited
        entry["time"] = now_iso()

        path = self.path(MEASUREMENTS_CSV)
        rows = _read_csv(path, lambda r: (r.get("case_id", ""), r.get("plane", "")))
        for m in metric_rows:
            row = dict(m, case_id=cid, edited=m["plane"] in edited, saved_at=now_iso())
            rows[(cid, m["plane"])] = row
        _write_csv(path, MEASUREMENT_COLUMNS, rows.values())

    def upsert_heights(self, cid, height_rows, dirty_heights):
        """height_rows: [{height, height_mm, ...}] from MeasurementEditor.height_rows()."""
        cid = str(cid)
        entry = self.meas_status.setdefault(cid, {})
        edited = list(entry.get("heights_edited", []))
        for key in dirty_heights:
            if key not in edited:
                edited.append(key)
        entry["heights_edited"] = edited
        entry["time"] = now_iso()

        path = self.path(HEIGHTS_CSV)
        rows = _read_csv(path, lambda r: (r.get("case_id", ""), r.get("height", "")))
        for h in height_rows:
            rows[(cid, h["height"])] = dict(h, case_id=cid, edited=h["height"] in edited, saved_at=now_iso())
        _write_csv(path, HEIGHT_COLUMNS, rows.values())
